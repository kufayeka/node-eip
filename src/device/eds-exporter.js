'use strict';

/**
 * ODVA Standard Electronic Data Sheet (EDS) Exporter
 *
 * Generates an official, standards-compliant .eds ASCII file from an
 * in-memory device specification (DeviceBuilder).
 */

const { getCipTypeInfo, CipDataTypeCode } = require('../cip/types');

function formatDate(d = new Date()) {
    const mm = String(d.getMonth() + 1).padStart(2, '0');
    const dd = String(d.getDate()).padStart(2, '0');
    const yyyy = d.getFullYear();
    return `${mm}-${dd}-${yyyy}`;
}

function formatTime(d = new Date()) {
    const hh = String(d.getHours()).padStart(2, '0');
    const mm = String(d.getMinutes()).padStart(2, '0');
    const ss = String(d.getSeconds()).padStart(2, '0');
    return `${hh}:${mm}:${ss}`;
}

/**
 * Exports device specification to ODVA EDS format string.
 *
 * @param {object} deviceSpec - Complete device model
 * @returns {string} Formatted EDS text
 */
function exportToEds(deviceSpec) {
    const identity = deviceSpec.identity || {};
    const params = deviceSpec.params || [];
    const assemblies = deviceSpec.assemblies || [];
    const now = new Date();

    const vendCode = identity.vendorId || 0xFFFF;
    const vendName = identity.vendorName || 'Generic Automation';
    const prodType = identity.deviceType !== undefined ? identity.deviceType : 0x002B; // 0x2B = Generic Device
    const prodTypeStr = identity.deviceTypeStr || 'Generic Device';
    const prodCode = identity.productCode || 1;
    const majRev = (identity.revision && identity.revision.major) || 1;
    const minRev = (identity.revision && identity.revision.minor) || 0;
    const prodName = identity.productName || 'Virtual EIP Device';
    const descText = deviceSpec.description || `${vendName} ${prodName} EDS File`;

    let eds = `$ ODVA Electronic Data Sheet (EDS)
$ Generated by @kufayeka/ethernet-ip DeviceBuilder
$ Timestamp: ${now.toISOString()}

[File]
    DescText = ${JSON.stringify(descText)};
    CreateDate = ${formatDate(now)};
    CreateTime = ${formatTime(now)};
    ModDate = ${formatDate(now)};
    ModTime = ${formatTime(now)};
    Revision = 1.0;
    HomeURL = "https://github.com/kufayeka/ethernet-ip";

[Device]
    VendCode = ${vendCode};
    VendName = ${JSON.stringify(vendName)};
    ProdType = ${prodType};
    ProdTypeStr = ${JSON.stringify(prodTypeStr)};
    ProdCode = ${prodCode};
    MajRev = ${majRev};
    MinRev = ${minRev};
    ProdName = ${JSON.stringify(prodName)};
`;

    // 1. [Params] Section
    if (params.length > 0) {
        eds += `\n[Params]\n`;
        for (const p of params) {
            const id = p.id;
            const typeInfo = getCipTypeInfo(p.dataType || 'INT');
            const typeCode = typeInfo ? typeInfo.code : CipDataTypeCode.INT;
            const byteSize = p.byteSize || (typeInfo ? typeInfo.size : 2);
            const descriptor = (p.access === 'rw') ? '0x0002' : '0x0001';
            const fullName = p.code ? `${p.code} ${p.name}` : p.name;
            const units = p.units || '';
            const help = p.help || '';
            const min = p.min !== undefined ? p.min : 0;
            const max = p.max !== undefined ? p.max : 65535;
            const defVal = p.default !== undefined ? p.default : 0;

            if (p.linkPath && p.linkPath.trim().length > 0) {
                eds += `    Param${id} =
        0,
        ${JSON.stringify(p.linkPath.trim())},
        ${descriptor},
        0x${typeCode.toString(16).padStart(4, '0').toUpperCase()},
        ${byteSize},
        ${JSON.stringify(fullName)},
        ${JSON.stringify(units)},
        ${JSON.stringify(help)},
        ${min}, ${max}, ${defVal};\n\n`;
            } else {
                eds += `    Param${id} =
        0,
        ,,
        ${descriptor},
        0x${typeCode.toString(16).padStart(4, '0').toUpperCase()},
        ${byteSize},
        ${JSON.stringify(fullName)},
        ${JSON.stringify(units)},
        ${JSON.stringify(help)},
        ${min}, ${max}, ${defVal};\n\n`;
            }
        }
    }

    // 2. [Assembly] Section
    if (assemblies.length > 0) {
        eds += `[Assembly]\n`;
        for (const assem of assemblies) {
            eds += `    Assem${assem.instance} =
        ${JSON.stringify(assem.name || `Assembly ${assem.instance}`)},
        ,
        ${assem.sizeBytes || 4},
        0x0000;\n\n`;

            if (Array.isArray(assem.members) && assem.members.length > 0) {
                assem.members.forEach((m, idx) => {
                    eds += `    Member${idx + 1} = Param${m.paramId || m.id}, ${m.bitOffset || 0}, ${m.bitLength || 16};\n`;
                });
                eds += `\n`;
            }
        }
    }

    // 3. [Connection Manager] Section
    const inputAssem = assemblies.find(a => a.type === 'input' || a.type === 'produce');
    const outputAssem = assemblies.find(a => a.type === 'output' || a.type === 'consume');

    if (inputAssem || outputAssem) {
        const toInstHex = (inputAssem ? inputAssem.instance : 101).toString(16).padStart(2, '0').toUpperCase();
        const otInstHex = (outputAssem ? outputAssem.instance : 100).toString(16).padStart(2, '0').toUpperCase();
        const toSize = inputAssem ? inputAssem.sizeBytes : 4;
        const otSize = outputAssem ? outputAssem.sizeBytes : 4;

        eds += `[Connection Manager]
    Connection1 =
        0x04010002,             $ Trigger: Cyclic, Transport Class 1
        0x44640405,             $ Point-to-Point, Exclusive Owner
        20000, ${toSize},       $ T->O RPI & Size
        20000, ${otSize},       $ O->T RPI & Size
        ,,
        ,,
        "Cyclic Class 1 I/O",
        "",
        "20 04 24 01 2C ${toInstHex} 2C ${otInstHex}";
`;
    }

    return eds;
}

module.exports = { exportToEds };
